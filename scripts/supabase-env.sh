#!/usr/bin/env bash
set -euo pipefail

# Generate supabase/.env with this project's own Supabase auth keys.
#
# The local Supabase CLI stack otherwise starts with the public demo keys that
# every CLI install shares, so any token minted for another local stack would
# also be valid here. supabase/config.toml reads the three values below via
# env(...); the CLI derives the anon and service_role JWTs from the JWT secret.
#
# The file is gitignored. An existing file is never overwritten: rotating keys
# invalidates every issued session and every client configured with the old
# keys, so delete the file yourself if that is what you want.
#
# Usage: bash scripts/supabase-env.sh

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${ROOT_DIR}/supabase/.env"

if [[ -e "${ENV_FILE}" ]]; then
  echo "supabase/.env already exists, not overwriting it."
  echo "Delete it first if you really want new keys (all sessions and clients using the old keys will break)."
  exit 1
fi

if ! command -v openssl >/dev/null 2>&1; then
  echo "openssl is required to generate random keys."
  exit 1
fi

# Random URL-safe string of exactly $1 characters.
rand_token() {
  local length="$1"
  local out=""
  while [[ ${#out} -lt ${length} ]]; do
    out+="$(openssl rand -base64 48 | tr -d '\n=+/')"
  done
  printf '%s' "${out:0:${length}}"
}

# Same shape as the CLI defaults: sb_<kind>_<22 chars>_<8 chars>.
jwt_secret="$(openssl rand -hex 32)"
publishable_key="sb_publishable_$(rand_token 22)_$(rand_token 8)"
secret_key="sb_secret_$(rand_token 22)_$(rand_token 8)"

umask 077
cat >"${ENV_FILE}" <<EOF
# Generated by scripts/supabase-env.sh. Do not commit.
JWT_SECRET=${jwt_secret}
SUPABASE_AUTH_PUBLISHABLE_KEY=${publishable_key}
SUPABASE_AUTH_SECRET_KEY=${secret_key}
EOF

echo "Wrote supabase/.env. Run 'npx supabase start', then 'npx supabase status -o env' for the keys."
